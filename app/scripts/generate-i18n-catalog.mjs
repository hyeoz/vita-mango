import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_ROOT = path.join(ROOT, "src");
const OUTPUT = path.join(SOURCE_ROOT, "i18n", "catalog.generated.ts");
const LANGUAGES = ["en", "ja", "fr", "es"];
const REFRESH = new Set(process.argv.slice(2));
const SENTINEL = "<<<VM_SPLIT_7E4B>>>";
const HANGUL = /[가-힣]/;

function normalize(value) {
  return value.replace(/\s+/g, " ").trim();
}

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (/\.(ts|tsx)$/.test(entry.name) && !entry.name.includes("catalog.generated")) files.push(full);
  }
  return files;
}

function collectNode(node, output) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isJsxText(node)) {
    const value = normalize(node.text);
    if (value && HANGUL.test(value)) output.add(value);
  }
  if (ts.isTemplateExpression(node)) {
    const parts = [node.head.text, ...node.templateSpans.map((span) => span.literal.text)];
    for (const part of parts) {
      const value = normalize(part);
      if (value && HANGUL.test(value)) output.add(value);
    }
  }
  ts.forEachChild(node, (child) => collectNode(child, output));
}

async function translateChunk(values, target) {
  const placeholders = values.map((value, valueIndex) => {
    const tokens = [];
    const protectedValue = value.replace(/\{\w+\}/g, (placeholder) => {
      const token = `⟦${valueIndex}_${tokens.length}⟧`;
      tokens.push({ token, placeholder });
      return token;
    });
    return { protectedValue, tokens };
  });
  const body = new URLSearchParams({
    client: "gtx",
    sl: "ko",
    tl: target,
    dt: "t",
    q: placeholders.map(({ protectedValue }) => protectedValue).join(`\n${SENTINEL}\n`),
  });
  const response = await fetch("https://translate.googleapis.com/translate_a/single", {
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded;charset=UTF-8" },
    body,
  });
  if (!response.ok) throw new Error(`Translation request failed (${target}): ${response.status}`);
  const json = await response.json();
  const translated = json[0].map((part) => part[0]).join("");
  const split = translated.split(SENTINEL).map((value) => normalize(value));
  if (split.length !== values.length) {
    throw new Error(`Translation response split mismatch (${target}): ${split.length}/${values.length}`);
  }
  return split.map((value, valueIndex) => {
    let restored = value;
    for (const { token, placeholder } of placeholders[valueIndex].tokens) {
      restored = restored.replace(token, placeholder);
    }
    return restored;
  });
}

async function translateAll(values, target) {
  const translated = [];
  let chunk = [];
  let size = 0;
  for (const value of values) {
    if (chunk.length && size + value.length > 9_000) {
      translated.push(...(await translateChunk(chunk, target)));
      chunk = [];
      size = 0;
    }
    chunk.push(value);
    size += value.length + SENTINEL.length + 2;
  }
  if (chunk.length) translated.push(...(await translateChunk(chunk, target)));
  return Object.fromEntries(values.map((value, index) => [value, translated[index]]));
}

async function loadExistingCatalog() {
  try {
    const source = await fs.readFile(OUTPUT, "utf8");
    const match = source.match(/export const GENERATED_CATALOG = ([\s\S]+) as const;\s*$/);
    return match ? JSON.parse(match[1]) : {};
  } catch (error) {
    if (error?.code === "ENOENT") return {};
    throw error;
  }
}

const strings = new Set();
for (const file of await walk(SOURCE_ROOT)) {
  const source = await fs.readFile(file, "utf8");
  const kind = file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  collectNode(ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, kind), strings);
}

const values = [...strings].sort((a, b) => a.localeCompare(b, "ko"));
const existing = await loadExistingCatalog();
const catalogs = {};
for (const language of LANGUAGES) {
  const current = REFRESH.has(language) ? {} : (existing[language] ?? {});
  const missing = values.filter((value) => !current[value]);
  const translated = missing.length ? await translateAll(missing, language) : {};
  catalogs[language] = Object.fromEntries(
    values.map((value) => [value, current[value] ?? translated[value]])
  );
}

const rendered = `// Generated by scripts/generate-i18n-catalog.mjs.\n` +
  `// Keep Korean source strings as stable keys; edit overrides.ts for copy fixes.\n` +
  `export const GENERATED_CATALOG = ${JSON.stringify(catalogs, null, 2)} as const;\n`;

await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
await fs.writeFile(OUTPUT, rendered);
console.log(`Wrote ${values.length} strings × ${LANGUAGES.length} languages to ${OUTPUT}`);

/** id → supplement, for fast lookup by the engine and the UI. */
export const BY_ID: Record<string, Supplement> = Object.fromEntries(
  SUPPLEMENTS.map((s) => [s.id, s])
);

/** Normalised name/alias → supplement, so user-typed names still resolve. */
export function normalizeName(name: string): string {
  return String(name ?? "")
    .normalize("NFC")
    .toLowerCase()
    .replace(/[\s\-_.·ㆍ/\\]/g, "");
}

const NAME_INDEX = new Map<string, Supplement>();
for (const s of SUPPLEMENTS) {
  NAME_INDEX.set(normalizeName(s.name), s);
  for (const a of s.aliases) NAME_INDEX.set(normalizeName(a), s);
}

export function findSupplement(name: string): Supplement | null {
  return NAME_INDEX.get(normalizeName(name)) ?? null;
}
